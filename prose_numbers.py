def compute(d):
    """{key: (value, deps)} for every number whose data is available."""
    out = {}
    with np.errstate(all="ignore"), warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        for key, (fn, deps, _doc) in definitions().items():
            if any(d.get(k) is None for k in deps):
                continue
            try:
                val = fn(d)
            except (KeyError, ValueError, IndexError, ZeroDivisionError):
                continue
            if "nan" in val or "inf" in val:    # e.g. an s.d. of one seed
                continue
            out[key] = (val, deps)
    return out


def tex_name(key):
    return "n" + "".join(p.capitalize() for p in key.split("_"))


def tex_value(s):
    s = s.replace("%", "\\%")
    if s[:1] in "+-" and s[1:2].isdigit():
        return f"${s[0]}${s[1:]}"
    return s


def write_tex(values):
    lines = ["% generated by make_tables.py from prose_numbers.py -- do not edit by hand",
             "% every number in main.tex is one of these macros"]
    defs = definitions()
    for key in sorted(values):
        lines.append(f"\\newcommand{{\\{tex_name(key)}}}"
                     f"{{{tex_value(values[key][0])}}}"
                     f"  % {defs[key][2]}")
    return "\n".join(lines) + "\n"


