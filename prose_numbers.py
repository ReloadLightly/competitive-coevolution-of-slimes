    def learning_cyclic_max(d):
        # the largest cyclic share among conditions whose runs learned
        out = 0.0
        conds = d["conditions"]["conditions"]
        for c, a in conds.items():
            if a.get("n_reached", 0) < a["n_runs"]:
                continue
            rows = within(d, c)
            dec = sum(v["triads_decided"] for v in rows)
            if dec:
                out = max(out, sum(v["cyclic"] for v in rows) / dec)
        return out
    add("cyclic_learning_max_pct", ["within", "conditions"],
        "largest pooled cyclic share among conditions in which every run "
        "learned to rally, in %")(lambda d: _pct(learning_cyclic_max(d), 1))

